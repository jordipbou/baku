#!/usr/bin/env python3
"""Regenerate test/expected-defuns.kl from the vendored Shen 43.2 corpus.

This is a development tool, never shipped and never used at runtime.  It is a
string-aware parser: a backslash is literal, '"' always terminates a string,
newlines inside strings are data, and top-level forms are counted by
parenthesis depth.  The generated file is a sorted, duplicate-free list of the
names defined by top-level (defun ...) forms; the reader test reads it and
compares it with the names found in the corpus.
"""

import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(HERE, "vendor", "shen-43.2", "klambda")
OUTPUT = os.path.join(HERE, "test", "expected-defuns.kl")


def top_level_forms(text):
    forms = []
    start = None
    depth = 0
    in_string = False
    for i, c in enumerate(text):
        if in_string:
            if c == '"':
                in_string = False
            continue
        if c == '"':
            if depth == 0 and start is None:
                start = i
            in_string = True
            continue
        if c == "(":
            if depth == 0:
                start = i
            depth += 1
            continue
        if c == ")":
            depth -= 1
            if depth == 0:
                forms.append(text[start:i + 1])
                start = None
            continue
    return forms


def main():
    names = set()
    files = sorted(glob.glob(os.path.join(CORPUS, "*.kl")))
    for path in files:
        with open(path, encoding="ascii") as handle:
            text = handle.read()
        for form in top_level_forms(text):
            match = re.match(r"\(defun\s+([^\s()\"]+)", form)
            if match:
                names.add(match.group(1))
    with open(OUTPUT, "w", encoding="ascii") as handle:
        handle.write("\\\\ Generated by tools/klambda_expected.py; do not edit.\n")
        for name in sorted(names):
            handle.write(name + "\n")
    print(f"wrote {len(names)} names to {OUTPUT}")


if __name__ == "__main__":
    sys.exit(main())
