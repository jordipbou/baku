#!/usr/bin/env python3
"""Regenerate test/expected-defuns.kl from the vendored Shen 43.2 corpus.

This is a development tool, never shipped and never used at runtime.  It uses
the shared string-aware parser in tools/klambda_parser.py: a backslash is
literal inside a string, '"' always terminates a string, newlines inside
strings are data, and top-level forms are parsed by parenthesis depth.  The
generated file is a sorted, duplicate-free list of the names defined by
top-level (defun ...) forms; the reader test reads it and compares it with the
names found in the corpus.
"""

import glob
import os
import sys

from klambda_parser import read_forms

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(HERE, "vendor", "shen-43.2", "klambda")
OUTPUT = os.path.join(HERE, "test", "expected-defuns.kl")


def defined_names(text):
    names = set()
    for form in read_forms(text):
        if isinstance(form, list) and len(form) >= 2 and form[0] == "defun":
            name = form[1]
            if isinstance(name, str):
                names.add(name)
    return names


def main():
    names = set()
    files = sorted(glob.glob(os.path.join(CORPUS, "*.kl")))
    for path in files:
        with open(path, encoding="ascii") as handle:
            names.update(defined_names(handle.read()))
    with open(OUTPUT, "w", encoding="ascii") as handle:
        handle.write("\\\\ Generated by tools/klambda_expected.py; do not edit.\n")
        for name in sorted(names):
            handle.write(name + "\n")
    print(f"wrote {len(names)} names to {OUTPUT}")


if __name__ == "__main__":
    sys.exit(main())
