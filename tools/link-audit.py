#!/usr/bin/env python3
"""Verify every link in the Baku project entry.

The documentation requirement says every link in ``proj.baku.org`` resolves to
content that exists.  The entry lives outside this repository (in the org
workspace), so this audit reads it at check time, extracts every org link, and
compares that ordered set with the committed ``docs/link-status.md`` record.

A link is either ``reachable`` (the live request got a 2xx or 3xx response after
redirects) or ``offline-accepted`` (a reviewed entry in ``OFFLINE_ACCEPTED``
with a date and reason).  Nothing is silently ignored: an added, removed or
reordered link makes the record stale, a dangling or unreachable link without a
reviewed acceptance fails the check, and an acceptance that the tool does not
list fails as well.

The committed record is generated by ``--write``, which performs the live
requests and refuses to write when a link is neither reachable nor accepted.
``--check`` repeats the live requests, so a link that dies later is caught.
``--offline`` skips the requests and validates only the record against the
entry.

Usage:

    python3 tools/link-audit.py --write
    python3 tools/link-audit.py --check
    python3 tools/link-audit.py --offline
    python3 tools/link-audit.py --self-test
"""

import argparse
import datetime
import re
import sys
import tempfile
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
DEFAULT_ENTRY = HERE.parent / "org" / "proj.baku.org"
RECORD = Path("docs") / "link-status.md"

USER_AGENT = "baku-link-audit/1.0"
ENTRY_NAME = "proj.baku.org"
STATES = ("reachable", "offline-accepted")

# Links that cannot be verified from this environment must be reviewed here,
# with a date and a reason.  The record is generated from this table, so a
# hand-written offline acceptance in docs/link-status.md fails the check.
OFFLINE_ACCEPTED = {}

LINK_RE = re.compile(r"\[\[(https?://[^\]\s]+)\](?:\[[^\]]*\])?\]")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ACCEPTED_NOTE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2}):\s+\S")
HEADER_RE = re.compile(r"^([A-Za-z ]+):\s+(.*?)\s*$")


@dataclass
class Fetch:
    state: str
    http: int
    final: str
    note: str


@dataclass
class Row:
    url: str
    state: str
    http: str
    final: str
    note: str


def extract_links(text):
    """Return the entry's http(s) links in order, without duplicates."""
    seen = set()
    links = []
    for match in LINK_RE.finditer(text):
        url = match.group(1)
        if url in seen:
            continue
        seen.add(url)
        links.append(url)
    return links


def fetch_url(url, timeout=20):
    """Fetch one link; classify the response instead of raising."""
    request = urllib.request.Request(
        url, headers={"User-Agent": USER_AGENT, "Accept": "text/html,*/*"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return Fetch("reachable", response.status, response.geturl(), "")
    except urllib.error.HTTPError as exc:
        return Fetch("dangling", exc.code, url,
                     f"HTTP {exc.code} {exc.reason}")
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        reason = getattr(exc, "reason", exc)
        return Fetch("unreachable", 0, url, f"network error: {reason}")


def escape_cell(value):
    return value.replace("|", "\\|")


def unescape_cell(value):
    return value.replace("\\|", "|")


def render(rows, checked_on):
    lines = [
        "# proj.baku.org link status",
        "",
        "Generated by `tools/link-audit.py --write`; do not hand-edit.",
        "Every link in the project entry is either reachable at the recorded",
        "check or explicitly accepted offline with a dated reason.",
        "",
        f"Entry: `{ENTRY_NAME}`",
        f"Checked on: {checked_on}",
        f"Links: {len(rows)}",
        "",
        "| Link | State | HTTP | Final URL | Note |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        cells = (row.url, row.state, row.http, row.final, row.note)
        lines.append("| " + " | ".join(escape_cell(c) for c in cells) + " |")
    lines.append("")
    return "\n".join(lines)


def parse_record(text):
    fields = {}
    rows = []
    for line in text.splitlines():
        header = HEADER_RE.match(line)
        if header:
            key = header.group(1).strip()
            if key in ("Entry", "Checked on", "Links"):
                fields[key] = header.group(2)
            continue
        stripped = line.strip()
        if not (stripped.startswith("|") and stripped.endswith("|")):
            continue
        cells = [unescape_cell(cell.strip())
                 for cell in stripped.strip("|").split("|")]
        if len(cells) != 5:
            continue
        if cells[0] == "Link" or all(re.fullmatch(r":?-+:?", c) for c in cells):
            continue
        rows.append(Row(*cells))
    return fields, rows


def validate_record(fields, rows, links, offline_accepted):
    violations = []
    checked = fields.get("Checked on")
    if not checked:
        violations.append(("docs/link-status.md", "missing Checked on date"))
    elif not DATE_RE.match(checked):
        violations.append(
            ("docs/link-status.md", f"Checked on is not an ISO date: {checked!r}"))
    count = fields.get("Links")
    if count is None:
        violations.append(("docs/link-status.md", "missing Links count"))
    elif not count.isdigit():
        violations.append(
            ("docs/link-status.md", f"Links is not a number: {count!r}"))
    elif int(count) != len(rows):
        violations.append(
            ("docs/link-status.md",
             f"Links is {count} but the table has {len(rows)} rows"))

    seen = set()
    for row in rows:
        label = row.url or "docs/link-status.md"
        if not row.url.startswith(("http://", "https://")):
            violations.append((label, f"not an http(s) link: {row.url!r}"))
        if row.url in seen:
            violations.append((label, "duplicate row"))
        seen.add(row.url)
        if row.state not in STATES:
            violations.append(
                (label, f"unknown state {row.state!r}"))
        elif row.state == "reachable":
            if not row.http.isdigit() or not 200 <= int(row.http) < 400:
                violations.append(
                    (label, f"reachable row has HTTP {row.http!r}"))
            if not row.final.startswith(("http://", "https://")):
                violations.append(
                    (label, f"reachable row has no final URL: {row.final!r}"))
        else:
            accepted = offline_accepted.get(row.url)
            if accepted is None:
                violations.append(
                    (label, "offline-accepted without a reviewed acceptance "
                            "in OFFLINE_ACCEPTED"))
            elif row.note != accepted:
                violations.append(
                    (label, "offline-accepted note does not match "
                            "OFFLINE_ACCEPTED"))
            if not ACCEPTED_NOTE_RE.match(row.note):
                violations.append(
                    (label, f"offline acceptance is not dated and reasoned: "
                            f"{row.note!r}"))

    if links is not None:
        recorded = [row.url for row in rows]
        if recorded != links:
            missing = [url for url in links if url not in recorded]
            extra = [url for url in recorded if url not in links]
            if missing:
                violations.append(
                    ("docs/link-status.md",
                     f"missing entry links: {', '.join(missing)}"))
            if extra:
                violations.append(
                    ("docs/link-status.md",
                     f"rows not in the entry: {', '.join(extra)}"))
            if not missing and not extra:
                violations.append(
                    ("docs/link-status.md",
                     "link order differs from the entry; regenerate with "
                     "--write"))
    return violations


def check_links(rows, fetch, offline_accepted, report):
    violations = []
    for row in rows:
        result = fetch(row.url)
        if result.state == "reachable":
            report.append(
                f"  {row.url}: reachable (HTTP {result.http})")
        elif row.state == "offline-accepted" and row.url in offline_accepted:
            report.append(
                f"  {row.url}: offline-accepted ({row.note})")
        else:
            violations.append(
                (row.url,
                 f"{result.state} ({result.note}) but the record says "
                 f"{row.state!r}"))
            report.append(
                f"  {row.url}: {result.state} ({result.note})")
    return violations


def load_entry(entry):
    if entry.is_file():
        return extract_links(entry.read_text(encoding="utf-8"))
    return None


def audit(root, entry, offline_accepted, fetch, verify, verbose):
    record = root / RECORD
    violations = []
    links = load_entry(entry)

    if links is None:
        note = "entry not found; checking the committed record only"
    else:
        note = str(entry)
    report = []

    if not record.is_file():
        violations.append(("docs/link-status.md", "missing link status record"))
        fields, rows = {}, []
    else:
        fields, rows = parse_record(record.read_text(encoding="utf-8"))
        violations.extend(
            validate_record(fields, rows, links, offline_accepted))

    if verify and rows:
        violations.extend(
            check_links(rows, fetch, offline_accepted, report))

    print("Link audit")
    print(f"  entry: {note}")
    print(f"  record: {record.relative_to(root)}")
    if fields.get("Checked on"):
        print(f"  checked on: {fields['Checked on']}")
    print(f"  links: {len(rows)}")
    if verbose or verify:
        for line in report:
            print(line)

    if violations:
        print("LINK-VIOLATIONS:")
        for label, reason in violations:
            print(f"  {label}: {reason}")

    ok = not violations
    print("LINK-AUDIT " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


def write_record(root, entry, offline_accepted, fetch, today):
    if not entry.is_file():
        print(f"LINK-AUDIT FAIL: entry not found: {entry}", file=sys.stderr)
        return 1
    links = extract_links(entry.read_text(encoding="utf-8"))
    if not links:
        print(f"LINK-AUDIT FAIL: no http(s) links in {entry}", file=sys.stderr)
        return 1

    rows = []
    violations = []
    for url in links:
        result = fetch(url)
        if result.state == "reachable":
            rows.append(Row(url, "reachable", str(result.http),
                            result.final, ""))
        elif url in offline_accepted:
            rows.append(Row(url, "offline-accepted", str(result.http),
                            result.final, offline_accepted[url]))
        else:
            violation = (url,
                         f"{result.state} ({result.note}); fix the link or "
                         f"add a dated OFFLINE_ACCEPTED entry")
            violations.append(violation)
            print(f"  {url}: {result.state} ({result.note})")

    if violations:
        print("LINK-VIOLATIONS:")
        for label, reason in violations:
            print(f"  {label}: {reason}")
        print("LINK-AUDIT FAIL")
        return 1

    record = root / RECORD
    record.parent.mkdir(parents=True, exist_ok=True)
    record.write_text(render(rows, today), encoding="utf-8")
    print(f"Wrote {record.relative_to(root)} with {len(rows)} links.")
    print("LINK-AUDIT PASS")
    return 0


def self_test():
    """Prove every failure path without touching the network."""
    good = Fetch("reachable", 200, "https://example.test/", "")

    def make_entry(root, extra=""):
        entry = root / "proj.baku.org"
        entry.write_text(
            "* Links\n"
            "- [[https://example.test/][Example]]\n"
            "- [[https://other.test/][Other]]\n"
            "%s" % extra, encoding="utf-8")
        return entry

    def fake_fetch(results):
        def fetch(url):
            value = results.get(url, good)
            if isinstance(value, Exception):
                raise value
            return value
        return fetch

    failures = []

    def expect(label, condition):
        if not condition:
            failures.append(label)

    with tempfile.TemporaryDirectory() as work:
        root = Path(work)
        (root / "docs").mkdir()
        entry = make_entry(root)
        rc = write_record(root, entry, {}, fake_fetch({}),
                          "2026-11-14")
        expect("write succeeds", rc == 0)
        text = (root / "docs/link-status.md").read_text(encoding="utf-8")
        fields, rows = parse_record(text)
        expect("two links recorded", len(rows) == 2)
        expect("record validates",
               not validate_record(fields, rows,
                                   extract_links(entry.read_text(encoding="utf-8")),
                                   {}))
        report = []
        expect("live check passes",
               not check_links(rows, fake_fetch({}), {}, report))

        # A new entry link makes the record stale.
        make_entry(root, "- [[https://new.test/][New]]\n")
        links = extract_links(entry.read_text(encoding="utf-8"))
        expect("missing entry link fails",
               any("missing entry links" in reason
                   for _, reason in validate_record(fields, rows, links, {})))

        # A row that names no entry link is stale too.
        stale_row = Row("https://stale.test/", "reachable", "200",
                        "https://stale.test/", "")
        expect("extra row fails",
               any("rows not in the entry" in reason
                   for _, reason in validate_record(fields, rows + [stale_row],
                                                    links, {})))

        # States must be known and consistent with the acceptance table.
        dangling = [Row(rows[0].url, "dangling", "404", rows[0].url, "")]
        expect("unknown state fails",
               any("unknown state" in reason
                   for _, reason in validate_record(fields, dangling, links, {})))
        unaccepted = [Row(rows[0].url, "offline-accepted", "0", rows[0].url,
                          "2026-11-14: no reviewed row")]
        expect("unreviewed acceptance fails",
               any("reviewed acceptance" in reason
                   for _, reason in validate_record(fields, unaccepted, links, {})))

        # The acceptance table and the record note must agree.
        local_accept = {rows[0].url:
                        "2026-11-14: reviewed offline acceptance for the test"}
        accepted_rows = [Row(rows[0].url, "offline-accepted", "0", rows[0].url,
                             local_accept[rows[0].url])]
        fields_one = dict(fields, **{"Links": "1"})
        expect("accepted row validates",
               not validate_record(fields_one, accepted_rows,
                                   [rows[0].url], local_accept))

        # Live results override a stale record.
        broken = {rows[0].url: Fetch("dangling", 404, rows[0].url, "HTTP 404")}
        expect("live dangling fails",
               check_links(rows, fake_fetch(broken), {}, []))
        down = {rows[0].url: Fetch("unreachable", 0, rows[0].url,
                                   "network error: down")}
        expect("live network failure fails",
               check_links(rows, fake_fetch(down), {}, []))
        expect("accepted live failure passes",
               not check_links(accepted_rows, fake_fetch(down), local_accept,
                               []))

        # Header damage is a violation.
        bad_date = validate_record(dict(fields, **{"Checked on": "yesterday"}),
                                   rows, None, {})
        expect("bad date fails",
               any("ISO date" in reason for _, reason in bad_date))
        bad_count = validate_record(dict(fields, **{"Links": "9"}),
                                    rows, None, {})
        expect("bad count fails",
               any("table has" in reason for _, reason in bad_count))

        # A missing record fails; a missing entry checks the record only.
        empty = root / "empty"
        empty.mkdir()
        (empty / "docs").mkdir()
        expect("missing record fails",
               audit(empty, entry, {}, fake_fetch({}), True, False) == 1)
        expect("missing entry uses the record",
               audit(root, root / "absent.org", {}, fake_fetch({}),
                     True, False) == 0)

        # The real writer refuses an unreachable link with no acceptance.
        unreachable = {rows[0].url: Fetch("unreachable", 0, rows[0].url,
                                          "network error: down")}
        write_accept = {rows[0].url:
                        "2026-11-14: reviewed offline acceptance for the test"}
        expect("unaccepted write fails",
               write_record(root, entry, {}, fake_fetch(unreachable),
                            "2026-11-14") == 1)
        expect("accepted write succeeds",
               write_record(root, entry, write_accept,
                            fake_fetch(unreachable), "2026-11-14") == 0)

    if failures:
        print("LINK-AUDIT SELF-TEST FAIL")
        for failure in failures:
            print(f"  {failure}")
        return 1
    print("LINK-AUDIT SELF-TEST PASS")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(HERE),
                        help="repository root containing docs/")
    parser.add_argument("--entry", default=str(DEFAULT_ENTRY),
                        help="project entry (default: ../org/proj.baku.org)")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true",
                      help="fetch every link and regenerate the record")
    mode.add_argument("--check", action="store_true",
                      help="validate the record and fetch every link")
    mode.add_argument("--offline", action="store_true",
                      help="validate the record without fetching")
    mode.add_argument("--self-test", action="store_true",
                      help="prove the record and failure paths on a fixture")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    root = Path(args.root).resolve()
    entry = Path(args.entry).expanduser().resolve()
    if args.write:
        today = datetime.date.today().isoformat()
        return write_record(root, entry, OFFLINE_ACCEPTED, fetch_url, today)
    return audit(root, entry, OFFLINE_ACCEPTED, fetch_url,
                 verify=args.check, verbose=args.verbose)


if __name__ == "__main__":
    sys.exit(main())
